    **为什么用 `<svg>` 内联而不是图标字体或图片**：① 字体图标在 16px 阈值下会糊；
    ② 图片不能继承颜色（要 7 张 × N 种颜色）；③ 内联 SVG 两者都满足，且零网络请求。

    ⚠️ **路径只写 `d`，不用 `<circle>`/`<rect>`**：这样整个图标就是「一串 `d`」，
    模板里一个 `v-for` 就够，不必为每个形状写一个 `v-if` 分支去和 TS 的联合类型较劲。
    圆是用两段圆弧路径写的（`a r r 0 1 0 2r 0` 那种），见下方注释。
